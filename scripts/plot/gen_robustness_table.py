"""
Generate LaTeX robustness ranking table from training logs.

Usage:
    python scripts/plot/gen_robustness_table.py
"""

import sys
import re
from pathlib import Path
import numpy as np
import pandas as pd

TRAIN_DIR = Path(__file__).resolve().parents[2] / "logs_std_train"


def parse_noise(dirname):
    result = {"obs": 0.0, "action": 0.0, "env": 0.0}
    m = re.search(r"NOISE_([\d.]+)", dirname)
    if m:
        result["obs"] = float(m.group(1))
    m = re.search(r"ACT_([\d.]+)", dirname)
    if m:
        result["action"] = float(m.group(1))
    m = re.search(r"ENV_([\d.]+)", dirname)
    if m:
        result["env"] = float(m.group(1))
    if not re.search(r"NOISE_", dirname):
        m = re.search(r"DS_([\d.]+)", dirname)
        if m:
            result["obs"] = float(m.group(1))
    if not re.search(r"ACT_", dirname):
        m = re.search(r"DA_([\d.]+)", dirname)
        if m:
            result["action"] = float(m.group(1))
    return result


def is_single_channel(noise):
    active = [ch for ch, v in noise.items() if v > 0]
    if len(active) == 0:
        return "clean"
    if len(active) == 1:
        return active[0]
    return None


def read_final_reward(run_dir, last_n=100):
    monitor = run_dir / "monitor.csv"
    if not monitor.exists():
        return None
    try:
        df = pd.read_csv(monitor, comment="#")
        if len(df) < 10:
            return None
        return float(np.mean(df["r"].iloc[-last_n:]))
    except Exception:
        return None


def collect_data(env, algo, last_n=100):
    env_algo_dir = TRAIN_DIR / f"{env}_{algo}"
    if not env_algo_dir.exists():
        return {}
    data = {"obs": {}, "action": {}, "env": {}}
    clean_rewards = []
    for run_dir in sorted(env_algo_dir.iterdir()):
        if not run_dir.is_dir():
            continue
        noise = parse_noise(run_dir.name)
        channel = is_single_channel(noise)
        if channel is None:
            continue
        reward = read_final_reward(run_dir, last_n)
        if reward is None:
            continue
        if channel == "clean":
            clean_rewards.append(reward)
        else:
            level = noise[channel]
            if level in data[channel]:
                data[channel][level] = max(data[channel][level], reward)
            else:
                data[channel][level] = reward
    if clean_rewards:
        clean_best = float(max(clean_rewards))
        for ch in data:
            data[ch][0.0] = clean_best
    return data


# Moderate noise levels per env (environment-appropriate scales)
MODERATE = {
    "evcharging": {"obs": [0.1, 0.2], "action": [0.1, 0.2], "env": [0.1, 0.2]},
    "building": {"obs": [0.05, 0.15], "action": [0.05, 0.15], "env": [0.5, 1.0]},
    "cogen": {"obs": [5.0, 10.0], "action": [0.1, 0.2], "env": [0.5, 1.0]},
}

ENV_NAMES = {
    "evcharging": "EV Charging",
    "building": "Building",
    "cogen": "Cogeneration",
}


def fmt_reward(val):
    """Format reward value compactly."""
    if abs(val) < 0.1:
        return f"{val:.3f}"
    if abs(val) < 10:
        return f"{val:.2f}"
    return f"{val:.1f}"


def fmt_delta(val):
    """Format delta with sign."""
    if abs(val) < 0.1:
        return f"{val:+.3f}"
    if abs(val) < 10:
        return f"{val:+.2f}"
    return f"{val:+.1f}"


def main():
    # Collect all data
    rows = []
    for env in ["evcharging", "building", "cogen"]:
        for algo in ["PPO", "SAC", "TD3"]:
            data = collect_data(env, algo)
            if not data or 0.0 not in data.get("obs", {}):
                continue
            clean = data["obs"][0.0]

            ch_results = {}
            for ch in ["obs", "action", "env"]:
                mod_levels = MODERATE[env][ch]
                mod_vals = [data[ch].get(l) for l in mod_levels if l in data.get(ch, {})]
                if mod_vals:
                    avg = np.mean(mod_vals)
                    pct = (avg - clean) / abs(clean) * 100 if abs(clean) > 1e-9 else 0
                    ch_results[ch] = (avg, pct)
                else:
                    ch_results[ch] = (None, None)
            rows.append((env, algo, clean, ch_results))

    # --- Generate LaTeX ---
    lines = []
    lines.append(r"% ============================================================")
    lines.append(r"% Table: Algorithm Noise Robustness Ranking")
    lines.append(r"% Auto-generated by scripts/plot/gen_robustness_table.py")
    lines.append(r"% ============================================================")
    lines.append(r"")
    lines.append(r"\begin{table}[htbp]")
    lines.append(r"\centering")
    lines.append(r"\caption{Algorithm robustness ranking under moderate noise. Environment-appropriate")
    lines.append(r"noise scales: EV Charging $\sigma \in \{0.1, 0.2\}$ for all channels;")
    lines.append(r"Building $\sigma_s, \sigma_a \in \{0.05, 0.15\}$, $\sigma_e \in \{0.5, 1.0\}$;")
    lines.append(r"Cogen $\sigma_s \in \{5, 10\}$, $\sigma_a \in \{0.1, 0.2\}$, $\sigma_e \in \{0.5, 1.0\}$.")
    lines.append(r"\textbf{Bold}: best robustness per environment and channel.")
    lines.append(r"\textsuperscript{\dag}: percentage unreliable (near-zero baseline).}")
    lines.append(r"\label{tab:robustness_ranking}")
    lines.append(r"\resizebox{\textwidth}{!}{%")
    lines.append(r"\begin{tabular}{@{}llr rrr rrr rrr@{}}")
    lines.append(r"\toprule")
    lines.append(r"& & & \multicolumn{3}{c}{\textbf{Observation Noise}}")
    lines.append(r"      & \multicolumn{3}{c}{\textbf{Action Noise}}")
    lines.append(r"      & \multicolumn{3}{c}{\textbf{Environment Noise}} \\")
    lines.append(r"\cmidrule(lr){4-6} \cmidrule(lr){7-9} \cmidrule(lr){10-12}")
    lines.append(r"\textbf{Environment} & \textbf{Algo} & \textbf{Clean}")
    lines.append(r"  & \textbf{Noisy} & \textbf{$\Delta$} & \textbf{\%}")
    lines.append(r"  & \textbf{Noisy} & \textbf{$\Delta$} & \textbf{\%}")
    lines.append(r"  & \textbf{Noisy} & \textbf{$\Delta$} & \textbf{\%} \\")
    lines.append(r"\midrule")

    envs = ["evcharging", "building", "cogen"]
    for env_idx, env in enumerate(envs):
        env_rows = [(a, c, cr) for (e, a, c, cr) in rows if e == env]
        n = len(env_rows)

        # Find best per channel (highest % = least degradation)
        best_ch = {}
        for ch in ["obs", "action", "env"]:
            pcts = [(a, cr[ch][1]) for (a, _, cr) in env_rows if cr[ch][1] is not None]
            if pcts:
                best_ch[ch] = max(pcts, key=lambda x: x[1])[0]

        for idx, (algo, clean, ch_res) in enumerate(env_rows):
            parts = []
            # Env column
            if idx == 0:
                parts.append(f"\\multirow{{{n}}}{{*}}{{{ENV_NAMES[env]}}}")
            else:
                parts.append("")

            parts.append(algo)
            parts.append(f"${fmt_reward(clean)}$")

            for ch in ["obs", "action", "env"]:
                noisy, pct = ch_res[ch]
                if noisy is None:
                    parts.extend(["---", "---", "---"])
                    continue

                delta = noisy - clean
                noisy_s = fmt_reward(noisy)
                delta_s = fmt_delta(delta)

                # Percentage: flag if baseline near zero and pct extreme
                if abs(clean) < 0.5 and abs(pct) > 100:
                    pct_s = "\\textsuperscript{\\dag}"
                else:
                    pct_s = f"{pct:+.1f}\\%"

                # Bold best
                is_best = best_ch.get(ch) == algo
                if is_best:
                    noisy_s = "\\textbf{" + noisy_s + "}"
                    pct_s = "\\textbf{" + pct_s + "}"

                parts.extend([f"${noisy_s}$", f"${delta_s}$", pct_s])

            line = "    " + " & ".join(parts) + " \\\\"
            lines.append(line)

        if env_idx < len(envs) - 1:
            lines.append(r"\midrule")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}%")
    lines.append(r"}")
    lines.append(r"\end{table}")

    output = "\n".join(lines)
    print(output)

    # Also save to file
    out_path = Path(__file__).resolve().parents[2] / "docs" / "thesis" / "tables" / "robustness_ranking.tex"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(output, encoding="utf-8")
    print(f"\n% Saved to: {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
